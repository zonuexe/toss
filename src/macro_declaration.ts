import { TossSyntaxError } from "./diagnostic.ts";
import { expandSyntax } from "./macro_expand_tree.ts";
import { LocalMacroRegistry } from "./macro_registry.ts";
import { parseSyntaxExpression } from "./macro_syntax_parse.ts";
import { type SyntaxGroup, syntaxGroup, type SyntaxNode } from "./syntax.ts";

const BUILTINS = new Set([
  "quote",
  "js",
  "jsImport",
  "import",
  "export",
  "extend",
  "super",
  "async",
  "await",
  "macroImport",
]);

export type MacroDeclaration = {
  readonly name: string;
  readonly blockSyntax: SyntaxGroup;
  readonly location: SyntaxGroup["origin"]["location"];
};

export function declaration(
  nodes: readonly SyntaxNode[],
): MacroDeclaration | undefined {
  const head = nodes[0];
  if (
    head?.kind !== "token" || head.spelling !== "%macro" ||
    !head.macroAdjacent
  ) return undefined;
  const form = nodes[1];
  if (nodes.length !== 2 || form?.kind !== "group" || form.delimiter !== "()") {
    throw new TossSyntaxError(
      head.origin.location,
      "Expected standalone %macro(#name, { parameter -> ... }). declaration.",
    );
  }
  const [name, comma, block] = form.children;
  if (
    form.children.length !== 3 || name?.kind !== "token" ||
    name.flavor !== "symbol" || comma?.kind !== "token" ||
    comma.spelling !== "," || block?.kind !== "group" ||
    block.delimiter !== "{}"
  ) {
    throw new TossSyntaxError(
      head.origin.location,
      "%macro requires a literal Named Symbol and a literal Block.",
    );
  }
  return {
    name: name.spelling.slice(1),
    blockSyntax: block,
    location: head.origin.location,
  };
}

export function register(
  item: MacroDeclaration,
  registry: LocalMacroRegistry,
): void {
  if (BUILTINS.has(item.name) || item.name === "macro") {
    throw new TossSyntaxError(
      item.location,
      `Cannot replace built-in macro %${item.name}.`,
    );
  }
  if (
    registry.definitions.some((definition) => definition.name === item.name)
  ) {
    throw new TossSyntaxError(item.location, `Duplicate macro %${item.name}.`);
  }
  const prepared = expandSyntax(
    item.blockSyntax.children,
    registry,
    0,
    item.name,
  );
  const expression = parseSyntaxExpression([
    syntaxGroup("{}", prepared, item.blockSyntax.origin),
  ], item.location);
  if (expression.kind !== "block" || expression.parameters.length !== 1) {
    throw new TossSyntaxError(
      item.location,
      "Macro expander must be a literal Block with exactly one parameter.",
    );
  }
  registry.register({
    name: item.name,
    block: expression,
    location: item.location,
    bodyStart: item.blockSyntax.origin.location,
    bodyEnd: prepared.at(-1)?.origin.location ??
      item.blockSyntax.origin.location,
  });
}

export function rejectGeneratedDeclarations(
  nodes: readonly SyntaxNode[],
): void {
  const visit = (node: SyntaxNode): void => {
    switch (node.kind) {
      case "group":
        node.children.forEach(visit);
        return;
      case "token":
        if (
          node.flavor === "macro" &&
          (node.spelling === "%macro" || node.spelling === "%export" ||
            node.spelling === "%macroImport") &&
          (node.origin.trace.length > 0 || node.spelling === "%macro" ||
            node.spelling === "%macroImport")
        ) {
          throw new TossSyntaxError(
            node.origin.location,
            `${node.spelling} cannot be generated by a macro.`,
          );
        }
        node.rawJavaScript?.prefix.forEach(visit);
        return;
      default:
        assertNever(node);
    }
  };
  nodes.forEach(visit);
}

export function rejectReplForms(nodes: readonly SyntaxNode[]): void {
  const unsupported = new Set([
    "%import",
    "%jsImport",
    "%macroImport",
    "%export",
  ]);
  const visit = (node: SyntaxNode): void => {
    switch (node.kind) {
      case "group":
        node.children.forEach(visit);
        return;
      case "token":
        if (unsupported.has(node.spelling)) {
          throw new TossSyntaxError(
            node.origin.location,
            `${node.spelling} is not supported in the initial REPL.`,
          );
        }
        node.rawJavaScript?.prefix.forEach(visit);
        return;
      default:
        assertNever(node);
    }
  };
  nodes.forEach(visit);
}

function assertNever(value: never): never {
  throw new TypeError(`Unexpected syntax node: ${JSON.stringify(value)}`);
}
