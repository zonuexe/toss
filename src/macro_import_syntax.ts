import type { SourceLocation } from "./diagnostic.ts";
import { TossSyntaxError } from "./diagnostic.ts";
import type {
  LocalMacroDefinition,
  LocalMacroRegistry,
} from "./macro_registry.ts";
import { parseSyntaxExpression } from "./macro_syntax_parse.ts";
import { readSyntax } from "./syntax_reader.ts";
import type { SyntaxNode } from "./syntax.ts";

export type MacroImportRequest = {
  readonly path: string;
  readonly location: SourceLocation;
};

export type ResolvedMacroImport = {
  readonly location: SourceLocation;
  readonly definitions: readonly LocalMacroDefinition[];
};

export function findMacroImports(
  source: string,
  file: string,
): readonly MacroImportRequest[] {
  const program = readSyntax(source, { file, deferUnclosedGroups: true });
  const imports: MacroImportRequest[] = [];
  let statement: SyntaxNode[] = [];
  for (const node of program.children) {
    if (isPeriod(node)) {
      const imported = macroImport(statement);
      if (imported !== undefined) imports.push(imported);
      else {
        const token = statement.find(isMacroImportToken);
        if (token !== undefined) {
          throw new TossSyntaxError(
            token.origin.location,
            "%macroImport is only valid as a standalone file-root directive.",
          );
        }
      }
      statement = [];
    } else statement.push(node);
  }
  const token = statement.find(isMacroImportToken);
  if (token !== undefined) {
    throw new TossSyntaxError(
      token.origin.location,
      "%macroImport declaration must end with a period.",
    );
  }
  return imports;
}

export function macroImport(
  nodes: readonly SyntaxNode[],
): MacroImportRequest | undefined {
  const head = nodes[0];
  if (!isMacroImportToken(head)) return undefined;
  const form = nodes[1];
  if (
    !head.macroAdjacent || nodes.length !== 2 || form?.kind !== "group" ||
    form.delimiter !== "()"
  ) {
    throw new TossSyntaxError(
      head.origin.location,
      "Expected standalone %macroImport('./relative.toss'). directive.",
    );
  }
  const path = form.children[0];
  if (
    form.children.length !== 1 || path?.kind !== "token" ||
    path.flavor !== "string"
  ) {
    throw new TossSyntaxError(
      head.origin.location,
      "%macroImport requires one literal String path.",
    );
  }
  const expression = parseSyntaxExpression([path], path.origin.location);
  if (expression.kind !== "string" || expression.value.length === 0) {
    throw new TossSyntaxError(
      path.origin.location,
      "%macroImport path must be a nonempty String.",
    );
  }
  if (
    !(expression.value.startsWith("./") ||
      expression.value.startsWith("../")) || !expression.value.endsWith(".toss")
  ) {
    throw new TossSyntaxError(
      path.origin.location,
      "%macroImport path must be relative and end in .toss.",
    );
  }
  return { path: expression.value, location: head.origin.location };
}

export function isMacroImportToken(
  node: SyntaxNode | undefined,
): node is Extract<SyntaxNode, { kind: "token" }> {
  return node?.kind === "token" && node.spelling === "%macroImport" &&
    node.flavor === "macro";
}

export function isPeriod(node: SyntaxNode): boolean {
  return node.kind === "token" && node.spelling === "." &&
    node.flavor === "ordinary";
}

export function findMacroImportToken(
  node: SyntaxNode,
): Extract<SyntaxNode, { kind: "token" }> | undefined {
  if (
    node.kind === "token" && node.spelling === "%macroImport" &&
    node.flavor === "macro"
  ) return node;
  if (node.kind === "group") {
    for (const child of node.children) {
      const found = findMacroImportToken(child);
      if (found !== undefined) return found;
    }
  } else {
    for (const child of node.rawJavaScript?.prefix ?? []) {
      const found = findMacroImportToken(child);
      if (found !== undefined) return found;
    }
  }
  return undefined;
}

export function containsMacroImport(nodes: readonly SyntaxNode[]): boolean {
  return nodes.some((node) => findMacroImportToken(node) !== undefined);
}

export function rejectGeneratedMacroImport(nodes: readonly SyntaxNode[]): void {
  const token = nodes.map(findMacroImportToken).find((item) =>
    item !== undefined
  );
  if (token !== undefined) {
    throw new TossSyntaxError(
      token.origin.location,
      "%macroImport cannot be generated by a macro.",
    );
  }
}

export function sameLocation(
  left: SourceLocation,
  right: SourceLocation,
): boolean {
  return left.file === right.file && left.line === right.line &&
    left.column === right.column;
}

export function registerImported(
  definition: LocalMacroDefinition,
  visibleAt: SourceLocation,
  registry: LocalMacroRegistry,
): void {
  if (
    [
      "quote",
      "js",
      "jsImport",
      "import",
      "export",
      "extend",
      "super",
      "async",
      "await",
      "macroImport",
      "macro",
    ].includes(definition.name)
  ) {
    throw new TossSyntaxError(
      visibleAt,
      `Cannot replace built-in macro %${definition.name}.`,
    );
  }
  if (
    registry.definitions.some((existing) =>
      existing.name === definition.name &&
      (existing.location.file === visibleAt.file ||
        existing.visibleAt?.file === visibleAt.file)
    )
  ) {
    throw new TossSyntaxError(
      visibleAt,
      `Duplicate macro %${definition.name}.`,
    );
  }
  registry.register({ ...definition, visibleAt });
}
